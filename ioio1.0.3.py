    def _format_decimal_for_rich(self, value: Optional[Decimal], precision: Optional[int] = None, default_precision_fallback: int = 2, add_commas: bool = False, highlight_negative: bool = False, default_style: str = "white", style_override: Optional[str] = None) -> Text:
        if value is None or (isinstance(value, Decimal) and value.is_nan()): return Text("N/A", style="dim")
        
        dp_to_use = precision if precision is not None else default_precision_fallback
        try:
            # Quantize to the desired decimal places
            quantizer = Decimal('1').scaleb(-dp_to_use)
            fmt_dec_val = value.quantize(quantizer, rounding=ROUND_HALF_EVEN)
            
            # Format with or without commas
            format_spec = f"{{:{',' if add_commas else ''}.{dp_to_use}f}}"
            display_str = format_spec.format(fmt_dec_val)
            
            current_style = style_override if style_override else default_style
            if highlight_negative and not style_override: # Only apply if no specific style override
                if fmt_dec_val < Decimal("0"): current_style = "bright_red"
                elif fmt_dec_val > Decimal("0"): current_style = "bright_green" # Positive PnL, etc.
            return Text(display_str, style=current_style)
        except (ValueError, TypeError, InvalidOperation) as e: 
            logger.error(f"Error formatting decimal '{value}' for Rich: {e}"); return Text("ERR", style="bold bright_red")

