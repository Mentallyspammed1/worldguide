    def run(self):
        self._display_startup_info()
        termux_notify(f"Pyrmethus Started", f"Trading {self.config.symbol} on {self.config.interval}.")
        cycle_count = 0
        while not self.shutdown_requested:
            cycle_count += 1
            cycle_start_monotonic = time.monotonic()
            logger.debug(f"{Fore.BLUE}--- Trading Cycle {cycle_count} Start ---{Style.RESET_ALL}")
            try: 
                self.trading_spell_cycle(cycle_count)
            except KeyboardInterrupt: 
                logger.warning("\nKeyboardInterrupt in main loop. Initiating shutdown."); self.shutdown_requested = True; break
            except ccxt.AuthenticationError as auth_err: 
                logger.critical(f"{Style.BRIGHT}{Fore.RED}CRITICAL AUTH ERROR (Cycle {cycle_count}): {auth_err}. Halting.{Style.RESET_ALL}",exc_info=False)
                termux_notify("Pyrmethus CRITICAL ERROR",f"Auth failed: {str(auth_err)[:100]}"); self.shutdown_requested=True; break
            except SystemExit as se: 
                logger.warning(f"SystemExit (code {se.code}) in trading cycle. Terminating."); self.shutdown_requested=True; break
            except Exception as cycle_err:
                logger.error(f"{Style.BRIGHT}{Fore.RED}Unhandled exception in trading cycle {cycle_count}: {cycle_err}{Style.RESET_ALL}", exc_info=True)
                termux_notify("Pyrmethus Cycle Error", f"Exception in cycle {cycle_count}. Check logs.")
                # Longer sleep after unhandled error in a cycle to prevent rapid error loops
                sleep_after_err = self.config.loop_sleep_seconds * 2 
                logger.info(f"Sleeping for {sleep_after_err}s after cycle error before retry."); time.sleep(sleep_after_err); continue
            
            cycle_duration = time.monotonic() - cycle_start_monotonic
            logger.debug(f"Cycle {cycle_count} completed in {cycle_duration:.2f}s.")
            
            if not self.shutdown_requested:
                sleep_needed = max(0, self.config.loop_sleep_seconds - cycle_duration)
                if sleep_needed > 0:
                    logger.debug(f"Sleeping for {sleep_needed:.2f}s until next cycle...")
                    # Sleep in small chunks to allow faster shutdown response
                    sleep_end_time = time.monotonic() + sleep_needed
                    try:
                        while time.monotonic() < sleep_end_time and not self.shutdown_requested:
                            time.sleep(min(0.5, sleep_needed)) # Sleep for 0.5s or remaining time
                    except KeyboardInterrupt: 
                        logger.warning("\nKeyboardInterrupt during sleep. Initiating shutdown."); self.shutdown_requested = True
            
            if self.shutdown_requested: logger.info("Shutdown requested. Exiting main trading loop."); break
        
        self.graceful_shutdown()
        console.print(f"\n[bold bright_cyan]Pyrmethus ({self.config.symbol}) has completed its session and returned to the ether.[/]")

    def trading_spell_cycle(self, cycle_num: int):
        # Initialize status dict for this cycle for the display panel
        current_status_dict: Dict[str, Any] = {"summary": f"Cycle {cycle_num} Processing...", "orig_detail": "N/A", "vt_detail": "N/A"}
        
        ohlcv_df = self.exchange_manager.fetch_ohlcv()
        if ohlcv_df is None or ohlcv_df.empty:
            logger.error(f"{Fore.RED}Cycle {cycle_num} Aborted: Failed to fetch OHLCV data.{Style.RESET_ALL}")
            current_status_dict.update({"summary": f"FAIL_CYCLE_{cycle_num}:FETCH_OHLCV"})
            self.status_display.print_status_panel(cycle_num, None, None, None, None, None, current_status_dict, self.order_manager.protection_tracker, self.exchange_manager.market_info); return

        try: # Extract latest price and timestamp
            latest_candle = ohlcv_df.iloc[-1]
            current_price = safe_decimal(latest_candle["close"])
            last_candle_ts = ohlcv_df.index[-1].to_pydatetime() # Convert Pandas Timestamp to datetime
            if current_price.is_nan() or current_price <= Decimal("0"): 
                raise ValueError(f"Invalid latest close price: {current_price.normalize() if not current_price.is_nan() else 'NaN'}")
            logger.debug(f"Latest Candle: Ts={last_candle_ts.strftime('%Y-%m-%d %H:%M:%S %Z')}, Price={current_price.normalize()}")
        except (IndexError, KeyError, ValueError, TypeError) as e:
            logger.error(f"{Fore.RED}Cycle {cycle_num} Aborted: Error processing latest candle: {e}{Style.RESET_ALL}")
            current_status_dict.update({"summary": f"FAIL_CYCLE_{cycle_num}:PROCESS_CANDLE ({type(e).__name__})"})
            self.status_display.print_status_panel(cycle_num, None, None, None, None, None, current_status_dict, self.order_manager.protection_tracker, self.exchange_manager.market_info); return

        indicators = self.indicator_calculator.calculate_indicators(ohlcv_df)
        if not indicators: # Includes critical ATR NaN case handled in calculator
            logger.error(f"{Fore.RED}Cycle {cycle_num} Aborted: Failed to calculate indicators.{Style.RESET_ALL}")
            current_status_dict.update({"summary": f"FAIL_CYCLE_{cycle_num}:CALC_INDICATORS"})
            self.status_display.print_status_panel(cycle_num, last_candle_ts, current_price, None, None, None, current_status_dict, self.order_manager.protection_tracker, self.exchange_manager.market_info); return
        
        indicators["close_price"] = current_price # Add current price for convenience in signal/exit checks

        total_equity, _ = self.exchange_manager.get_balance()
        if total_equity is None or total_equity.is_nan() or total_equity <= Decimal("0"):
            equity_val_str = str(total_equity.normalize() if total_equity and not total_equity.is_nan() else total_equity)
            logger.error(f"{Fore.RED}Cycle {cycle_num} Aborted: Invalid total equity ({equity_val_str}) or zero/negative.{Style.RESET_ALL}")
            current_status_dict.update({"summary": f"FAIL_CYCLE_{cycle_num}:FETCH_EQUITY_INVALID"})
            self.status_display.print_status_panel(cycle_num, last_candle_ts, current_price, indicators, None, total_equity, current_status_dict, self.order_manager.protection_tracker, self.exchange_manager.market_info); return

        current_positions = self.exchange_manager.get_current_position()
        if current_positions is None:
            logger.error(f"{Fore.RED}Cycle {cycle_num} Aborted: Failed to fetch current position.{Style.RESET_ALL}")
            current_status_dict.update({"summary": f"FAIL_CYCLE_{cycle_num}:FETCH_POSITION"})
            self.status_display.print_status_panel(cycle_num, last_candle_ts, current_price, indicators, None, total_equity, current_status_dict, self.order_manager.protection_tracker, self.exchange_manager.market_info); return

        active_pos_side: Optional[str] = None; active_pos_details: Optional[Dict[str,Any]] = None
        if current_positions.get("long",{}): active_pos_side, active_pos_details = "long", current_positions["long"]
        elif current_positions.get("short",{}): active_pos_side, active_pos_details = "short", current_positions["short"]

        if active_pos_side and active_pos_details: # Currently in a position
            pos_qty = safe_decimal(active_pos_details.get("qty"))
            pos_entry_px = safe_decimal(active_pos_details.get("entry_price"))
            current_atr = indicators.get("atr", Decimal("NaN")) # type: ignore
            
            # Manage TSL if applicable (only if SL/TP is active, not if TSL already active)
            if (self.order_manager.protection_tracker.get(active_pos_side) == "ACTIVE_SLTP" and 
                not any(v.is_nan() or v <= Decimal("0") for v in [pos_entry_px, current_price, current_atr])): # type: ignore
                self.order_manager.manage_trailing_stop(active_pos_side, pos_entry_px, current_price, current_atr) # type: ignore
                # If TSL was activated, re-fetch position to reflect new protection status for display
                if self.order_manager.protection_tracker.get(active_pos_side) == "ACTIVE_TSL":
                    logger.debug("Re-fetching position summary after TSL management for display update."); 
                    current_positions = self.exchange_manager.get_current_position() # Update positions
                    if current_positions: active_pos_details = current_positions.get(active_pos_side, {}) # Update details
                    else: active_pos_details = None # Failed to fetch, clear details
            
            # Check for strategy-based exit signals if TSL is not yet managing the exit
            if self.order_manager.protection_tracker.get(active_pos_side) != "ACTIVE_TSL":
                exit_reason = self.signal_generator.check_exit_signals(active_pos_side, indicators)
                if exit_reason:
                    logger.trade(f"Attempting to close {active_pos_side.upper()} position due to: {exit_reason}")
                    if not pos_qty.is_nan() and pos_qty > Decimal("0"): # type: ignore
                        close_ok = self.order_manager.close_position(active_pos_side, pos_qty, reason=exit_reason) # type: ignore
                        current_status_dict.update({"summary": f"CLOSED_{active_pos_side.upper()}_SIGNAL: {exit_reason.split(':')[0]}" if close_ok else f"FAIL:CLOSE_SIGNAL_{active_pos_side.upper()}"}) # Shorten reason for summary
                        current_positions = self.exchange_manager.get_current_position() # Update after close attempt
                        self.status_display.print_status_panel(cycle_num, last_candle_ts, current_price, indicators, current_positions, total_equity, current_status_dict, self.order_manager.protection_tracker, self.exchange_manager.market_info); return
                    else: logger.warning(f"Exit signal for {active_pos_side.upper()} but pos qty invalid ({pos_qty}). Cannot close.")
            
            # Re-check position state after all actions (TSL, exit signals) to see if it was closed by exchange stops
            current_positions_after_actions = self.exchange_manager.get_current_position()
            if current_positions_after_actions is None: 
                logger.warning(f"Failed to re-fetch position state for {active_pos_side} after TSL/exit checks. Status may be stale.")
            else:
                current_positions = current_positions_after_actions # Update main variable
                # Determine if still in position
                new_long_pos, new_short_pos = current_positions.get("long",{}), current_positions.get("short",{})
                if new_long_pos and safe_decimal(new_long_pos.get("qty","0")).copy_abs() >= POSITION_QTY_EPSILON: active_pos_side, active_pos_details = "long", new_long_pos
                elif new_short_pos and safe_decimal(new_short_pos.get("qty","0")).copy_abs() >= POSITION_QTY_EPSILON: active_pos_side, active_pos_details = "short", new_short_pos
                else: # Position is now flat
                    if active_pos_side: # Implies it was closed during this cycle by exchange stop or other means
                        logger.info(f"Position {active_pos_side.upper()} appears closed by exchange stop or earlier action during cycle.");
                        current_status_dict.update({"summary": f"INFO:POS_{active_pos_side.upper()}_CLOSED_EXCH_OR_SIGNAL"})
                        self.order_manager.protection_tracker[active_pos_side.lower()] = None # Reset tracker
                    active_pos_side, active_pos_details = None, None # Now flat

        if not active_pos_side: # Flat, check for new entry signals
            logger.debug("Currently flat. Checking for new entry signals...")
            entry_signals_result = self.signal_generator.generate_signals(ohlcv_df, indicators)
            current_status_dict = entry_signals_result # Update status with signal generation outcome
            
            entry_order_side: Optional[str] = "buy" if entry_signals_result.get("long") else "sell" if entry_signals_result.get("short") else None
            if entry_order_side:
                current_atr = indicators.get("atr", Decimal("NaN")) # type: ignore
                if not current_atr.is_nan() and current_atr > Decimal("0"): # type: ignore
                    entry_ok = self.order_manager.place_risked_market_order(entry_order_side, current_atr, total_equity, current_price) # type: ignore
                    entered_side_logical = "long" if entry_order_side == "buy" else "short"
                    # Update status based on entry attempt outcome for the panel
                    current_status_dict.update({"summary": f"ENTERED_{entered_side_logical.upper()}" if entry_ok else f"FAIL:ENTRY_{entered_side_logical.upper()}"})
                    current_positions = self.exchange_manager.get_current_position() # Refresh position state
                    self.status_display.print_status_panel(cycle_num, last_candle_ts, current_price, indicators, current_positions, total_equity, current_status_dict, self.order_manager.protection_tracker, self.exchange_manager.market_info); return
                else: 
                    logger.warning(f"Cannot attempt {entry_order_side.upper()} entry: Missing/invalid ATR ({current_atr}).")
                    current_status_dict.update({"summary": f"FAIL:ENTRY_DATA_MISSING_ATR_{entry_order_side.upper()}"})
        else: # Still in position, update status for display
            current_status_dict.update({"summary": f"HOLDING_{active_pos_side.upper()}"})
        
        # Default display if no early return from entry/exit actions
        self.status_display.print_status_panel(cycle_num, last_candle_ts, current_price, indicators, current_positions, total_equity, current_status_dict, self.order_manager.protection_tracker, self.exchange_manager.market_info)

